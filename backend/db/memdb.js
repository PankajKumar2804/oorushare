/**
 * db/memdb.js — In-memory data store (pg.Pool drop-in)
 *
 * Used automatically when DATABASE_URL is not set (see db/migrate.js).
 * Implements the pg Pool interface (.query(sql, params)) by pattern-matching
 * SQL strings — no actual database required.
 *
 * Design:
 *   - Four in-memory arrays mirror the four PostgreSQL tables:
 *       spots, bookings, queue (dispatch_queue), credits
 *   - Auto-incrementing ID counters simulate SERIAL PRIMARY KEY
 *   - seedDemo() pre-populates realistic Bengaluru demo data on startup
 *   - All query patterns are matched in order: spots → bookings → credits → queue
 *
 * Limitations (acceptable for demo / development):
 *   - No transactions — concurrent writes are not atomic
 *   - Data is lost on process restart
 *   - Only the SQL patterns generated by OoruShare routes are handled;
 *     arbitrary queries will fall through to the empty-rows default
 */

