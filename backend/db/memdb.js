// Fake pg Pool interface
const pool = {
  async query(sql, params = []) {
    const s = sql.trim().replace(/\s+/g, ' ').toLowerCase();

    // ── SPOTS ──────────────────────────────────────────────────────
    // NOTE: group-by check MUST come before the general SELECT FROM spots branch
    if (s.includes('group by rwa_status')) {
      // rwa stats — count spots by rwa_status
      const map = { pending: 0, approved: 0, rejected: 0 };
      spots.forEach(sp => {
        const k = sp.rwa_status || 'approved';
        if (map[k] !== undefined) map[k]++;
      });
      return { rows: Object.entries(map).filter(([,c]) => c > 0).map(([rwa_status, count]) => ({ rwa_status, count: String(count) })) };
    }
    if (s.startsWith('select * from spots') || s.startsWith('select id, lat') || (s.startsWith('select') && s.includes('from spots'))) {
      let rows = [...spots];
      // Filter out rejected/pending spots unless query explicitly checks rwa_status or selects all
      if (s.includes("rwa_status = 'approved'")) {
        rows = rows.filter(r => r.rwa_status === 'approved');
      }
      // Apply each filter based on param values
      const clauses = s.match(/and (\w+) = \$\d+/g) || [];
      clauses.forEach((clause, i) => {
        const col = clause.match(/and (\w+) =/)[1];
        const val = params[i];
        if (col === 'neighborhood') rows = rows.filter(r => r.neighborhood === val);
        else if (col === 'status')  rows = rows.filter(r => r.status === val);
        else if (col === 'owner_name') rows = rows.filter(r => r.owner_name === val);
        else if (col === 'rwa_status') rows = rows.filter(r => r.rwa_status === val);
      });
      const idMatch = s.match(/where id\s*=\s*(\$1|\d+)/);
      if (idMatch) {
        const idVal = idMatch[1] === '$1' ? parseInt(params[0]) : parseInt(idMatch[1]);
        rows = rows.filter(r => r.id === idVal);
      } else if (s.includes('where id =')) {
        rows = rows.filter(r => r.id === parseInt(params[0]));
      }
      return { rows };
    }
    if (s.startsWith('insert into spots')) {
      const [owner_name, address, neighborhood, lat, lng, gate_width_m, available_from, available_to] = params;
      const spot = { id: nextId('spots'), owner_name, address, neighborhood, lat: parseFloat(lat), lng: parseFloat(lng), gate_width_m: parseFloat(gate_width_m)||3, available_from, available_to, status: 'available', rwa_status: 'approved', created_at: now() };
      spots.push(spot);
      return { rows: [spot] };
    }
    if (s.startsWith('update spots set status')) {
      // Two forms:
      //   PATCH /spots/:id/status  →  UPDATE spots SET status = $1 WHERE id = $2  (params: [status, id])
      //   bookings route           →  UPDATE spots SET status = 'booked' WHERE id = $1  (params: [id], status in SQL)
      //   auto-release             →  UPDATE spots SET status = 'available' WHERE id = $1 AND status = 'booked'  (params: [id])
      let status, id;
      const inlineMatch = s.match(/set status = '([^']+)'/);
      if (inlineMatch) {
        status = inlineMatch[1];
        const whereNum = s.match(/where id\s*=\s*(\d+)/);
        id = whereNum ? parseInt(whereNum[1]) : params[0];
      } else {
        [status, id] = params;
      }
      const spot = spots.find(r => r.id === parseInt(id));
      if (spot) spot.status = status;
      return { rows: spot ? [spot] : [] };
    }
    if (s.startsWith("update spots set rwa_status = 'approved'")) {
      const spot = spots.find(r => r.id === parseInt(params[0]));
      if (spot) spot.rwa_status = 'approved';
      return { rows: spot ? [spot] : [] };
    }
    if (s.startsWith("update spots set rwa_status = 'rejected'")) {
      const spot = spots.find(r => r.id === parseInt(params[0]));
      if (spot) spot.rwa_status = 'rejected';
      return { rows: spot ? [spot] : [] };
    }
    // ── COUNT QUERIES ─────────────────────────────────────────────
    if (s.includes('count(*)') && s.includes('from bookings')) {
      return { rows: [{ cnt: bookings.length }] };
    }
    if (s.includes('count(*)') && s.includes('from spots')) {
      const cnt = s.includes("rwa_status = 'approved'")
        ? spots.filter(r => r.rwa_status === 'approved').length
        : spots.length;
      return { rows: [{ cnt }] };
    }

    // ── BOOKINGS ───────────────────────────────────────────────────
    if (s.startsWith('select * from bookings') || s.includes('from bookings')) {
      let rows = [...bookings];
      if (s.includes('spot_id =')) rows = rows.filter(r => r.spot_id === parseInt(params[0]));
      rows.sort((a,b) => new Date(b.booked_at) - new Date(a.booked_at));
      if (s.includes('limit 100')) rows = rows.slice(0, 100);
      return { rows };
    }
    if (s.startsWith("select * from spots where id = $1 and status = 'available'")) {
      return { rows: spots.filter(r => r.id === parseInt(params[0]) && r.status === 'available') };
    }
    if (s.startsWith('insert into bookings')) {
      const [spot_id, rider_name, rider_phone, platform, duration_mins] = params;
      const b = { id: nextId('bookings'), spot_id: parseInt(spot_id), rider_name, rider_phone, platform, duration_mins: parseInt(duration_mins)||2, status: 'active', booked_at: now() };
      bookings.push(b);
      return { rows: [b] };
    }
    if (s.startsWith("update bookings set status = 'completed'")) {
      const b = bookings.find(r => r.id === parseInt(params[0]));
      if (b) b.status = 'completed';
      return { rows: [] };
    }
    if (s.startsWith("update bookings set status = 'cancelled'")) {
      const b = bookings.find(r => r.id === parseInt(params[0]));
      if (b) b.status = 'cancelled';
      return { rows: b ? [b] : [] };
    }

    // ── CREDITS ────────────────────────────────────────────────────
    if (s.startsWith('select * from credits') || s.startsWith('select credits from credits')) {
      let rows = [...credits];
      if (s.includes('owner_name =')) rows = rows.filter(r => r.owner_name === params[0]);
      rows.sort((a,b) => new Date(b.created_at) - new Date(a.created_at));
      return { rows };
    }
    if (s.startsWith('select c.owner_name')) {
      // credits summary: total credits minus any redeemed credits
      const map = {};
      credits.forEach(c => {
        const spot = spots.find(s_ => s_.id === c.spot_id);
        const key = c.owner_name;
        if (!map[key]) map[key] = { owner_name: c.owner_name, total_credits: 0, share_count: 0, neighborhood: spot?.neighborhood || '' };
        map[key].total_credits += parseFloat(c.credits);
        map[key].share_count++;
      });
      // Deduct redemptions
      redemptions.forEach(r => {
        if (map[r.owner_name]) {
          map[r.owner_name].total_credits = Math.max(0, map[r.owner_name].total_credits - parseFloat(r.credits_used));
        }
      });
      return { rows: Object.values(map).sort((a,b) => b.total_credits - a.total_credits) };
    }
    if (s.startsWith('insert into credits')) {
      // Two forms: with explicit values or SELECT-based
      if (s.includes('select owner_name')) {
        const [spot_id, booking_id, reason_suffix] = params;
        const spot = spots.find(s_ => s_.id === parseInt(spot_id));
        if (!spot) return { rows: [] };
        const c = { id: nextId('credits'), owner_name: spot.owner_name, spot_id: parseInt(spot_id), booking_id: parseInt(booking_id), credits: 10, reason: `Driveway share — ${reason_suffix}`, created_at: now() };
        credits.push(c);
        return { rows: [c] };
      }
      const [owner_name, spot_id, credits_, reason] = params;
      const c = { id: nextId('credits'), owner_name, spot_id: parseInt(spot_id), booking_id: null, credits: parseFloat(credits_), reason, created_at: now() };
      credits.push(c);
      return { rows: [c] };
    }

    // ── REDEMPTIONS ────────────────────────────────────────────────
    if (s.startsWith('select * from redemptions') || s.includes('from redemptions')) {
      let rows = [...redemptions];
      if (s.includes('owner_name =')) rows = rows.filter(r => r.owner_name === params[0]);
      rows.sort((a,b) => new Date(b.created_at) - new Date(a.created_at));
      return { rows };
    }
    if (s.startsWith('insert into redemptions')) {
      const [owner_name, credits_used, inr_value, benefit_type] = params;
      const r = { id: nextId('redemptions'), owner_name, credits_used: parseFloat(credits_used), inr_value: parseFloat(inr_value), benefit_type: benefit_type || 'RWA_MAINTENANCE_OFFSET', status: 'approved', created_at: now() };
      redemptions.push(r);
      return { rows: [r] };
    }

    // ── PARTNER DISPATCHES ─────────────────────────────────────────
    if (s.startsWith('select * from partner_dispatches') || s.includes('from partner_dispatches')) {
      let rows = [...partnerDispatches];
      rows.sort((a,b) => new Date(b.created_at) - new Date(a.created_at));
      return { rows };
    }
    if (s.startsWith('insert into partner_dispatches')) {
      const [platform, order_id, rider_name, dest_lat, dest_lng, allocated_spot_id, booking_id] = params;
      const p = { id: nextId('partner_dispatches'), platform, order_id, rider_name, dest_lat: parseFloat(dest_lat), dest_lng: parseFloat(dest_lng), allocated_spot_id: allocated_spot_id ? parseInt(allocated_spot_id) : null, booking_id: booking_id ? parseInt(booking_id) : null, status: 'dispatched', created_at: now() };
      partnerDispatches.push(p);
      return { rows: [p] };
    }

    // ── QUEUE ──────────────────────────────────────────────────────
    if (s.startsWith('select * from dispatch_queue')) {
      let rows = [...queue];
      if (s.includes('store_name ='))   { const v = params.find(p => typeof p === 'string' && !['pending','dispatched','completed'].includes(p) && !['hsr layout','indiranagar','koramangala'].includes(p?.toLowerCase())); if(v) rows = rows.filter(r => r.store_name === v); }
      if (s.includes('neighborhood =')) { const nb = ['HSR Layout','Indiranagar','Koramangala'].find(n => params.includes(n)); if(nb) rows = rows.filter(r => r.neighborhood === nb); }
      if (s.includes("status = 'pending'") || (s.includes('status =') && params.includes('pending'))) rows = rows.filter(r => r.status === 'pending');
      rows.sort((a,b) => new Date(a.scheduled_at) - new Date(b.scheduled_at));
      if (s.includes('limit 20')) rows = rows.slice(0, 20);
      return { rows };
    }
    if (s.startsWith('select max(scheduled_at)')) {
      const storeParam = params[0];
      const pending = queue.filter(q_ => q_.store_name === storeParam && q_.status === 'pending');
      const last = pending.reduce((max, q_) => !max || new Date(q_.scheduled_at) > new Date(max) ? q_.scheduled_at : max, null);
      return { rows: [{ last_dispatch: last }] };
    }
    if (s.startsWith('insert into dispatch_queue')) {
      const [store_name, neighborhood, rider_name, platform, scheduled_at] = params;
      const q_ = { id: nextId('queue'), store_name, neighborhood, rider_name, platform, scheduled_at, status: 'pending', spot_id: null, created_at: now() };
      queue.push(q_);
      return { rows: [q_] };
    }
    if (s.startsWith("update dispatch_queue set status = 'dispatched'")) {
      const q_ = queue.find(r => r.id === parseInt(params[0]));
      if (q_) q_.status = 'dispatched';
      return { rows: q_ ? [q_] : [] };
    }
    if (s.startsWith('select neighborhood')) {
      // queue stats
      const map = {};
      queue.forEach(q_ => {
        if (!map[q_.neighborhood]) map[q_.neighborhood] = { neighborhood: q_.neighborhood, pending: 0, dispatched: 0, completed: 0 };
        map[q_.neighborhood][q_.status] = (map[q_.neighborhood][q_.status] || 0) + 1;
      });
      return { rows: Object.values(map) };
    }

    // ── SCHEMA / MIGRATION (no-op in mem mode) ────────────────────
    if (s.startsWith('create table') || s.startsWith('create index') || s.startsWith('delete from')) {
      return { rows: [] };
    }

    // ── PIPELINE RUNS (sdlc-poc compat, not used here) ────────────
    return { rows: [] };
  },
  async end() {}
};

